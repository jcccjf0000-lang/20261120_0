# 載入需要的套件
# 我們可以使用一個簡單的關鍵字評分規則，或是利用常見的工具來模擬5個等級的情緒分析

def analyze_sentiment(text):
    """
    分析輸入文字的情緒，並將其分類為 1 至 5 個等級。
    1: 非常差 (Very Negative)
    2: 差 (Negative)
    3: 普通 (Neutral)
    4: 好 (Positive)
    5: 非常好 (Very Positive)
    """
    # 轉為小寫方便比對
    text_lower = text.lower()

    # 定義正面與負面的關鍵字詞
    very_positive_words = ['非常好', '太棒了', '完美', '超級好用', '100分', '極力推薦', 'excellent', 'perfect', 'awesome']
    positive_words = ['好用', '不錯', '推薦', '喜歡', '滿意', 'good', 'nice', 'like']
    negative_words = ['不好', '不推薦', '普通', '普通而已', '差', '爛', '失望', 'bad', 'disappointed', 'normal']
    very_negative_words = ['非常差', '極度失望', '垃圾', '再也不買', '爛透了', 'terrible', 'worst', 'awful']

    # 進行簡單的權重計算
    score = 3 # 預設為普通

    # 檢查極度正面
    if any(word in text_lower for word in very_positive_words):
        score = 5
    # 檢查正面
    elif any(word in text_lower for word in positive_words):
        score = 4
    # 檢查極度負面
    elif any(word in text_lower for word in very_negative_words):
        score = 1
    # 檢查負面
    elif any(word in text_lower for word in negative_words):
        score = 2

    return score

# --- 測試輸入區 ---
test_reviews = [
    "這產品非常好用，用過之後就回不去了，超級推薦！",
    "產品還不錯，品質還可以，推薦購買。",
    "用起來感覺普通，沒有想像中的驚艷。",
    "有點失望，品質不太好，不怎麼推薦。",
    "這真的是爛透了，極度失望，千萬不要買！"
]

print("=== 情緒分析測試結果 (1-5等評分) ===")
for idx, review in enumerate(test_reviews, 1):
    rating = analyze_sentiment(review)
    print(f"測試 {idx}: {review}")
    print(f"=> 評分結果 (1-5): {rating} 星\n")

# 您也可以在此處輸入自訂的文字進行測試：
